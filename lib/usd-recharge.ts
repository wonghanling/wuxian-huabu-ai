// ============================================================
// 美元充值档位（Stripe）
//
// 记账货币只有一个:人民币。美元充值按下表换成人民币入账，
// 扣费 / 退款 / 账单全部沿用现有的人民币逻辑，一处未改。
//
// 为什么不存两个余额字段:
// 一旦库里同时有 balance_cny 和 balance_usd，就必须回答"扣费先扣哪个""两边
// 都不够但加起来够呢""汇率变了历史余额要不要重算""退款退回哪个" —— 每个问题
// 都会变成客诉。所以美元只是展示与收款的单位，不是记账单位。
// ============================================================

/**
 * 对用户标的汇率:1 USD = 6.00 CNY。取整数是为了让用户一眼能算
 * ($10 = ¥60)，不必查表。
 *
 * 它低于真实汇率(约 6.75)是有意的 —— Stripe 跨境费率 3.9% + $0.30，
 * 用户付 $10 你实收约 $9.31、折合 ¥62.8。按真实汇率给 ¥67 就等于每笔
 * 自己垫 ¥4；按 6.00 给 ¥60，手续费被覆盖，每档都不亏。
 *
 * 不接实时汇率:标价会浮动(今天 $14 明天 $14.2)，还得处理汇率 API
 * 挂掉时的兜底。改汇率只动这一个常量。
 */
export const USD_CNY_RATE = 6.0;

export interface UsdTier {
  /** Stripe 收款金额（美元） */
  usd: number;
  /** 入账的人民币余额 */
  cny: number;
  /** 相对基准档的额外赠送，用于 UI 标注；0 表示无 */
  bonusPercent: number;
}

/**
 * 档位表:cny = usd × 6.00，无额外赠送。
 *
 * 每档实际毛利(已扣 Stripe 3.9% + $0.30，按真实汇率 6.7481 折算):
 *   $10  → 给 ¥60   实收约 ¥62.8   赚 ¥2.8
 *   $20  → 给 ¥120  实收约 ¥127.7  赚 ¥7.7
 *   $50  → 给 ¥300  实收约 ¥322.2  赚 ¥22.2
 *   $100 → 给 ¥600  实收约 ¥646.5  赚 ¥46.5
 *
 * 不设 $5 档:它只赚 ¥0.4，而提现路径(Stripe → 香港 → 人民币)还要再过
 * 两道手续费，算下来是亏的。最低档定在 $10。
 */
export const USD_TIERS: UsdTier[] = [
  { usd: 10,  cny: 60,  bonusPercent: 0 },
  { usd: 20,  cny: 120, bonusPercent: 0 },
  { usd: 50,  cny: 300, bonusPercent: 0 },
  { usd: 100, cny: 600, bonusPercent: 0 },
];

/** 按美元金额取档位。找不到返回 null —— 金额必须来自本表，不信任前端传值 */
export function findUsdTier(usd: number): UsdTier | null {
  return USD_TIERS.find((t) => t.usd === usd) ?? null;
}

/** 人民币余额换算成美元展示值（仅用于界面，不参与记账） */
export function cnyToUsdDisplay(cny: number): number {
  return Math.round((cny / USD_CNY_RATE) * 100) / 100;
}
